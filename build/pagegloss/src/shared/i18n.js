  var LANGUAGE_LABELS = { zh: '中文', en: 'English' };

  function detectLanguage(preferred) {
    var candidates = [];
    if (preferred) candidates.push(preferred);
    try {
      if (typeof chrome !== 'undefined' && chrome.i18n && chrome.i18n.getUILanguage) {
        candidates.push(chrome.i18n.getUILanguage());
      }
    } catch (err) { /* ignore */ }
    if (typeof navigator !== 'undefined' && navigator.language) candidates.push(navigator.language);
    for (var i = 0; i < candidates.length; i++) {
      var value = String(candidates[i] || '').toLowerCase();
      if (!value) continue;
      if (value.indexOf('zh') === 0 || value.indexOf('cn') === 0) return 'zh';
      return 'en';
    }
    return 'zh';
  }

  function format(template, values) {
    if (!values) return template;
    return String(template).replace(/%[sn]/g, function (token) {
      if (token === '%n') {
        return values.n == null ? '' : String(values.n);
      }
      return values.s == null ? '' : String(values.s);
    });
  }

  function createI18n(language) {
    var lang = MESSAGES[language] ? language : detectLanguage(language);
    return {
      lang: lang,
      label: LANGUAGE_LABELS[lang] || lang,
      t: function (key, values) {
        var table = MESSAGES[lang] || MESSAGES.zh;
        var template = table[key];
        if (template == null) template = (MESSAGES.zh[key] != null ? MESSAGES.zh[key] : key);
        return format(template, values);
      }
    };
  }

  var api = { create: createI18n, detectLanguage: detectLanguage, MESSAGES: MESSAGES, format: format };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  if (typeof window !== 'undefined') window.PageGlossI18n = api;
